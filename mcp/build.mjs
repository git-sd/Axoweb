// Bundles the shared checks into one file so the server runs with a plain `node server.mjs`.
import { build } from "esbuild";

await build({
  entryPoints: ["entry.ts"],
  outfile: "checks.bundle.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  alias: { "@": "../app" },
  nodePaths: ["../app/node_modules"],
  banner: { js: "// Generated by `npm run build` from ../app/lib. Do not edit." },
  logLevel: "info",
});
